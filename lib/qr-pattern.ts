export const QR_REVEAL_SECONDS = 20;

export function qrTextureData() {
  const values = new Float32Array(QR_SIZE * QR_SIZE);
  for (let y = 0; y < QR_MODULES.length; y++) for (let x = 0; x < QR_MODULES.length; x++) {
    // Upload bottom-to-top for WebGL's UV origin.
    values[(QR_SIZE - 1 - y - QR_MARGIN) * QR_SIZE + x + QR_MARGIN] = Number(QR_MODULES[y][x]);
  }
  return values;
}
